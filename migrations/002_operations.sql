create table if not exists operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY primary key,
    operation_type text CONSTRAINT operation_type_invalid CHECK (operation_type in ('deposit', 'withdraw', 'transfer')) not null,
    operation_date timestamptz not null default now(),
    user_id bigint CONSTRAINT user_id_positive CHECK (user_id > 0) not null,
    recipient_id bigint CONSTRAINT recipient_id_positive CHECK (recipient_id > 0)
        CONSTRAINT recipient_id_different_user_id CHECK (recipient_id <> user_id)
        CONSTRAINT recipient_id_is_null_when_not_transfer CHECK (operation_type = 'transfer' OR recipient_id IS NULL)
        CONSTRAINT recipient_id_not_null_when_transfer CHECK (operation_type <> 'transfer' OR recipient_id IS NOT NULL),
    amount bigint CONSTRAINT amount_positive CHECK (amount > 0) not null,
    comment text default ''
);

